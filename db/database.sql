BEGIN;

DROP TABLE IF EXISTS order_items CASCADE;
DROP TABLE IF EXISTS orders CASCADE;
DROP TABLE IF EXISTS stock_items CASCADE;
DROP TABLE IF EXISTS variants CASCADE;
DROP TABLE IF EXISTS products CASCADE;
DROP TABLE IF EXISTS manufacturers CASCADE;
DROP TABLE IF EXISTS subcategories CASCADE;
DROP TABLE IF EXISTS categories CASCADE;
DROP TABLE IF EXISTS users CASCADE;
DROP TABLE IF EXISTS roles CASCADE;

-- Справочник ролей пользователей.
CREATE TABLE roles (
    role_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_code VARCHAR(20) NOT NULL UNIQUE,
    role_name VARCHAR(50) NOT NULL UNIQUE
);

-- Пользователи системы. Логин уникален без учёта регистра.
CREATE TABLE users (
    user_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login       VARCHAR(50) NOT NULL UNIQUE,
    last_name   VARCHAR(100) NOT NULL,
    first_name  VARCHAR(100) NOT NULL,
    middle_name VARCHAR(100) NOT NULL DEFAULT '',
    role_id     INTEGER NOT NULL REFERENCES roles (role_id) ON DELETE RESTRICT
);
CREATE UNIQUE INDEX users_login_lower_key ON users (lower(login));

-- Справочники каталога.
CREATE TABLE categories (
    category_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE subcategories (
    subcategory_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subcategory_name VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE manufacturers (
    manufacturer_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    manufacturer_name VARCHAR(100) NOT NULL UNIQUE
);

-- Модель товара: артикул уникален, цена не может быть отрицательной.
CREATE TABLE products (
    product_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    article         VARCHAR(20) NOT NULL UNIQUE,
    category_id     INTEGER NOT NULL REFERENCES categories (category_id) ON DELETE RESTRICT,
    subcategory_id  INTEGER NOT NULL REFERENCES subcategories (subcategory_id) ON DELETE RESTRICT,
    manufacturer_id INTEGER NOT NULL REFERENCES manufacturers (manufacturer_id) ON DELETE RESTRICT,
    name            VARCHAR(200) NOT NULL,
    image_path      VARCHAR(300),
    material        VARCHAR(200) NOT NULL,
    description     TEXT NOT NULL,
    price           NUMERIC(12, 2) NOT NULL CHECK (price >= 0)
);

-- Вариант исполнения задаёт цвет изделия.
CREATE TABLE variants (
    variant_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    variant_name VARCHAR(100) NOT NULL UNIQUE
);

-- Складская позиция: пара модель-вариант и доступный остаток.
CREATE TABLE stock_items (
    stock_item_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id    INTEGER NOT NULL REFERENCES products (product_id) ON DELETE RESTRICT,
    variant_id    INTEGER NOT NULL REFERENCES variants (variant_id) ON DELETE RESTRICT,
    quantity      INTEGER NOT NULL DEFAULT 0 CHECK (quantity >= 0),
    CONSTRAINT stock_items_product_variant_key UNIQUE (product_id, variant_id)
);

-- Заказ: дата и клиент.
CREATE TABLE orders (
    order_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_date TIMESTAMP NOT NULL,
    user_id    INTEGER NOT NULL REFERENCES users (user_id) ON DELETE RESTRICT
);

-- Состав заказа: цена фиксируется на момент оформления.
CREATE TABLE order_items (
    order_item_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id      INTEGER NOT NULL REFERENCES orders (order_id) ON DELETE CASCADE,
    stock_item_id INTEGER NOT NULL REFERENCES stock_items (stock_item_id) ON DELETE RESTRICT,
    quantity      INTEGER NOT NULL CHECK (quantity > 0),
    unit_price    NUMERIC(12, 2) NOT NULL CHECK (unit_price >= 0)
);

CREATE INDEX orders_order_date_idx ON orders (order_date);
CREATE INDEX order_items_order_id_idx ON order_items (order_id);
CREATE INDEX stock_items_product_id_idx ON stock_items (product_id);

