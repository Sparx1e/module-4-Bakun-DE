"""Сборка готового SQL-скрипта БД из исходных CSV-файлов заказчика.

Скрипт нужен только для подготовки поставки: он читает resources/import/*.csv
и формирует db/database.sql. В самом приложении импорт CSV не выполняется.
"""

from __future__ import annotations

import csv
from pathlib import Path

BASE_DIR = Path(__file__).resolve().parent.parent
IMPORT_DIR = BASE_DIR / "resources" / "import"
OUTPUT_PATH = BASE_DIR / "db" / "database.sql"

ROLE_CODES = {
    "Администратор": "admin",
    "Менеджер": "manager",
    "Клиент": "client",
}


def read_csv(name: str) -> list[dict[str, str]]:
    """Читает CSV заказчика: разделитель «;», кодировка UTF-8 с BOM."""
    path = IMPORT_DIR / name
    with path.open("r", encoding="utf-8-sig", newline="") as stream:
        return list(csv.DictReader(stream, delimiter=";"))


def sql_text(value: str | None) -> str:
    """Экранирует строку для SQL-литерала."""
    if value is None or value == "":
        return "NULL"
    return "'" + value.replace("'", "''") + "'"


def sql_date_time(value: str) -> str:
    """Преобразует значение исходной даты в SQL-литерал TIMESTAMP."""
    return "'" + value.strip() + "'"


def unique_in_order(values: list[str]) -> list[str]:
    """Уникальные значения с сохранением порядка появления."""
    seen: set[str] = set()
    result: list[str] = []
    for value in values:
        if value not in seen:
            seen.add(value)
            result.append(value)
    return result


def build() -> str:
    products = read_csv("Products_import.csv")
    variants = read_csv("Variants_import.csv")
    stock_items = read_csv("Stock_Items_import.csv")
    users = read_csv("Users_import.csv")
    orders = read_csv("Orders_import.csv")
    order_items = read_csv("Order_Items_import.csv")

    roles = unique_in_order([row["role"] for row in users])
    categories = unique_in_order([row["category"] for row in products])
    subcategories = unique_in_order([row["subcategory"] for row in products])
    manufacturers = unique_in_order([row["manufacturer"] for row in products])

    category_ids = {name: index + 1 for index, name in enumerate(categories)}
    subcategory_ids = {name: index + 1 for index, name in enumerate(subcategories)}
    manufacturer_ids = {name: index + 1 for index, name in enumerate(manufacturers)}
    role_ids = {name: index + 1 for index, name in enumerate(roles)}

    lines: list[str] = []
    add = lines.append

    add("-- ФормаДесерт: схема и данные базы данных PostgreSQL")
    add("-- Модули 1-4. Скрипт создаёт структуру в третьей нормальной форме")
    add("-- и загружает исходные данные заказчика (24 модели, 2 варианта,")
    add("-- 48 складских позиций, 8 пользователей, 18 заказов, 24 строки состава).")
    add("--")
    add("-- Запуск: psql -U postgres -d formadessert -f db/database.sql")
    add("")
    add("BEGIN;")
    add("")
    add("DROP TABLE IF EXISTS order_items CASCADE;")
    add("DROP TABLE IF EXISTS orders CASCADE;")
    add("DROP TABLE IF EXISTS stock_items CASCADE;")
    add("DROP TABLE IF EXISTS variants CASCADE;")
    add("DROP TABLE IF EXISTS products CASCADE;")
    add("DROP TABLE IF EXISTS manufacturers CASCADE;")
    add("DROP TABLE IF EXISTS subcategories CASCADE;")
    add("DROP TABLE IF EXISTS categories CASCADE;")
    add("DROP TABLE IF EXISTS users CASCADE;")
    add("DROP TABLE IF EXISTS roles CASCADE;")
    add("")
    add("-- Справочник ролей пользователей.")
    add("CREATE TABLE roles (")
    add("    role_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,")
    add("    role_code VARCHAR(20) NOT NULL UNIQUE,")
    add("    role_name VARCHAR(50) NOT NULL UNIQUE")
    add(");")
    add("")
    add("-- Пользователи системы. Логин уникален без учёта регистра.")
    add("CREATE TABLE users (")
    add("    user_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,")
    add("    login       VARCHAR(50) NOT NULL UNIQUE,")
    add("    last_name   VARCHAR(100) NOT NULL,")
    add("    first_name  VARCHAR(100) NOT NULL,")
    add("    middle_name VARCHAR(100) NOT NULL DEFAULT '',")
    add("    role_id     INTEGER NOT NULL REFERENCES roles (role_id) ON DELETE RESTRICT")
    add(");")
    add("CREATE UNIQUE INDEX users_login_lower_key ON users (lower(login));")
    add("")
    add("-- Справочники каталога.")
    add("CREATE TABLE categories (")
    add("    category_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,")
    add("    category_name VARCHAR(100) NOT NULL UNIQUE")
    add(");")
    add("")
    add("CREATE TABLE subcategories (")
    add("    subcategory_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,")
    add("    subcategory_name VARCHAR(100) NOT NULL UNIQUE")
    add(");")
    add("")
    add("CREATE TABLE manufacturers (")
    add("    manufacturer_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,")
    add("    manufacturer_name VARCHAR(100) NOT NULL UNIQUE")
    add(");")
    add("")
    add("-- Модель товара: артикул уникален, цена не может быть отрицательной.")
    add("CREATE TABLE products (")
    add("    product_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,")
    add("    article         VARCHAR(20) NOT NULL UNIQUE,")
    add("    category_id     INTEGER NOT NULL REFERENCES categories (category_id) ON DELETE RESTRICT,")
    add("    subcategory_id  INTEGER NOT NULL REFERENCES subcategories (subcategory_id) ON DELETE RESTRICT,")
    add("    manufacturer_id INTEGER NOT NULL REFERENCES manufacturers (manufacturer_id) ON DELETE RESTRICT,")
    add("    name            VARCHAR(200) NOT NULL,")
    add("    image_path      VARCHAR(300),")
    add("    material        VARCHAR(200) NOT NULL,")
    add("    description     TEXT NOT NULL,")
    add("    price           NUMERIC(12, 2) NOT NULL CHECK (price >= 0)")
    add(");")
    add("")
    add("-- Вариант исполнения задаёт цвет изделия.")
    add("CREATE TABLE variants (")
    add("    variant_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,")
    add("    variant_name VARCHAR(100) NOT NULL UNIQUE")
    add(");")
    add("")
    add("-- Складская позиция: пара модель-вариант и доступный остаток.")
    add("CREATE TABLE stock_items (")
    add("    stock_item_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,")
    add("    product_id    INTEGER NOT NULL REFERENCES products (product_id) ON DELETE RESTRICT,")
    add("    variant_id    INTEGER NOT NULL REFERENCES variants (variant_id) ON DELETE RESTRICT,")
    add("    quantity      INTEGER NOT NULL DEFAULT 0 CHECK (quantity >= 0),")
    add("    CONSTRAINT stock_items_product_variant_key UNIQUE (product_id, variant_id)")
    add(");")
    add("")
    add("-- Заказ: дата и клиент.")
    add("CREATE TABLE orders (")
    add("    order_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,")
    add("    order_date TIMESTAMP NOT NULL,")
    add("    user_id    INTEGER NOT NULL REFERENCES users (user_id) ON DELETE RESTRICT")
    add(");")
    add("")
    add("-- Состав заказа: цена фиксируется на момент оформления.")
    add("CREATE TABLE order_items (")
    add("    order_item_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,")
    add("    order_id      INTEGER NOT NULL REFERENCES orders (order_id) ON DELETE CASCADE,")
    add("    stock_item_id INTEGER NOT NULL REFERENCES stock_items (stock_item_id) ON DELETE RESTRICT,")
    add("    quantity      INTEGER NOT NULL CHECK (quantity > 0),")
    add("    unit_price    NUMERIC(12, 2) NOT NULL CHECK (unit_price >= 0)")
    add(");")
    add("")
    add("CREATE INDEX orders_order_date_idx ON orders (order_date);")
    add("CREATE INDEX order_items_order_id_idx ON order_items (order_id);")
    add("CREATE INDEX stock_items_product_id_idx ON stock_items (product_id);")
    add("")
    add("-- Справочник ролей.")
    add("INSERT INTO roles (role_id, role_code, role_name) VALUES")
    role_rows = [
        f"    ({role_ids[name]}, {sql_text(ROLE_CODES[name])}, {sql_text(name)})"
        for name in roles
    ]
    add(",\n".join(role_rows) + ";")
    add("")
    add("-- Пользователи (8 записей).")
    add("INSERT INTO users (user_id, login, last_name, first_name, middle_name, role_id) VALUES")
    user_rows = [
        "    ({user_id}, {login}, {last_name}, {first_name}, {middle_name}, {role_id})".format(
            user_id=row["user_id"],
            login=sql_text(row["login"]),
            last_name=sql_text(row["last_name"]),
            first_name=sql_text(row["first_name"]),
            middle_name=sql_text(row["middle_name"]),
            role_id=role_ids[row["role"]],
        )
        for row in users
    ]
    add(",\n".join(user_rows) + ";")
    add("")
    add("-- Справочники каталога.")
    add("INSERT INTO categories (category_id, category_name) VALUES")
    add(",\n".join(f"    ({category_ids[name]}, {sql_text(name)})" for name in categories) + ";")
    add("")
    add("INSERT INTO subcategories (subcategory_id, subcategory_name) VALUES")
    add(",\n".join(f"    ({subcategory_ids[name]}, {sql_text(name)})" for name in subcategories) + ";")
    add("")
    add("INSERT INTO manufacturers (manufacturer_id, manufacturer_name) VALUES")
    add(",\n".join(f"    ({manufacturer_ids[name]}, {sql_text(name)})" for name in manufacturers) + ";")
    add("")
    add("-- Модели товаров (24 записи). Для FD0024 путь к изображению пуст:")
    add("-- приложение подставляет ресурс picture.png.")
    add("INSERT INTO products (product_id, article, category_id, subcategory_id, manufacturer_id,")
    add("                       name, image_path, material, description, price) VALUES")
    product_rows = []
    for row in products:
        product_rows.append(
            "    ({pid}, {article}, {cid}, {sid}, {mid}, {name}, {image}, {material}, {description}, {price})".format(
                pid=row["product_id"],
                article=sql_text(row["article"]),
                cid=category_ids[row["category"]],
                sid=subcategory_ids[row["subcategory"]],
                mid=manufacturer_ids[row["manufacturer"]],
                name=sql_text(row["name"]),
                image=sql_text(row["image"]),
                material=sql_text(row["material"]),
                description=sql_text(row["description"]),
                price=row["price"],
            )
        )
    add(",\n".join(product_rows) + ";")
    add("")
    add("-- Варианты исполнения (2 записи).")
    add("INSERT INTO variants (variant_id, variant_name) VALUES")
    add(",\n".join(
        f"    ({row['variant_id']}, {sql_text(row['variant_name'])})" for row in variants
    ) + ";")
    add("")
    add("-- Складские позиции (48 записей). Остатки уже учитывают исторические заказы.")
    add("INSERT INTO stock_items (stock_item_id, product_id, variant_id, quantity) VALUES")
    add(",\n".join(
        "    ({sid}, {pid}, {vid}, {qty})".format(
            sid=row["stock_item_id"],
            pid=row["product_id"],
            vid=row["variant_id"],
            qty=row["quantity"],
        )
        for row in stock_items
    ) + ";")
    add("")
    add("-- Исторические заказы (18 записей).")
    add("INSERT INTO orders (order_id, order_date, user_id) VALUES")
    add(",\n".join(
        "    ({oid}, {date}, {uid})".format(
            oid=row["order_id"],
            date=sql_date_time(row["order_date"]),
            uid=row["user_id"],
        )
        for row in orders
    ) + ";")
    add("")
    add("-- Состав исторических заказов (24 записи).")
    add("INSERT INTO order_items (order_item_id, order_id, stock_item_id, quantity, unit_price) VALUES")
    add(",\n".join(
        "    ({iid}, {oid}, {sid}, {qty}, {price})".format(
            iid=row["order_item_id"],
            oid=row["order_id"],
            sid=row["stock_item_id"],
            qty=row["quantity"],
            price=row["unit_price"],
        )
        for row in order_items
    ) + ";")
    add("")
    add("-- После явных идентификаторов возвращаем последовательности на нужную позицию.")
    for table, column in (
        ("roles", "role_id"),
        ("users", "user_id"),
        ("categories", "category_id"),
        ("subcategories", "subcategory_id"),
        ("manufacturers", "manufacturer_id"),
        ("products", "product_id"),
        ("variants", "variant_id"),
        ("stock_items", "stock_item_id"),
        ("orders", "order_id"),
        ("order_items", "order_item_id"),
    ):
        add(
            f"SELECT setval(pg_get_serial_sequence('{table}', '{column}'), "
            f"COALESCE((SELECT MAX({column}) FROM {table}), 1));"
        )
    add("")
    add("COMMIT;")
    add("")
    add("-- Контрольные запросы после восстановления:")
    add("-- SELECT COUNT(*) FROM products;      -- 24")
    add("-- SELECT COUNT(*) FROM variants;      -- 2")
    add("-- SELECT COUNT(*) FROM stock_items;   -- 48")
    add("-- SELECT COUNT(*) FROM users;         -- 8")
    add("-- SELECT COUNT(*) FROM orders;        -- 18")
    add("-- SELECT COUNT(*) FROM order_items;   -- 24")
    add("-- SELECT SUM(quantity) FROM stock_items;")
    add("")

    return "\n".join(lines)


def main() -> None:
    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT_PATH.write_text(build(), encoding="utf-8")
    print(f"Записан {OUTPUT_PATH}")


if __name__ == "__main__":
    main()
